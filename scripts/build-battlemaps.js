'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'library', 'battlemaps', 'data.js');

const BOOKS = [
  { folder: 'Towns and Taverns/Little-Book-Towns-Taverns-VTT', book: 'Towns & Taverns — Little Book', prefix: 'TTLB', sides: true },
  { folder: 'Towns and Taverns/Towns-Taverns-Vol1-VTT', book: 'Towns & Taverns — Volume 1', prefix: 'TTB1', sides: true },
  { folder: 'Towns and Taverns/Towns-Taverns-Vol2-VTT', book: 'Towns & Taverns — Volume 2', prefix: 'TTB2', sides: true }
];

const SIDE_NAMES = { l: 'left', r: 'right', lr: 'spread', v: 'variant' };

function slugify(s) {
  return s
    .toLowerCase()
    .replace(/_/g, ' ')
    .replace(/[^a-z0-9 ]+/g, ' ')
    .trim()
    .replace(/\s+/g, '-');
}

function parseEntry(cfg, filename) {
  const base = path.basename(filename, path.extname(filename));
  let rest = base;
  let grid = true;
  if (/-NoGrid-VTT$/i.test(rest)) { grid = false; rest = rest.replace(/-NoGrid-VTT$/i, ''); }
  else if (/-No-Grid-VTT$/i.test(rest)) { grid = false; rest = rest.replace(/-No-Grid-VTT$/i, ''); }
  else if (/-VTT$/i.test(rest)) { rest = rest.replace(/-VTT$/i, ''); }
  else throw new Error('Unknown grid token: ' + filename);

  const m = rest.match(/^(TTLB|TTB1|TTB2|LB|V1|V2)-P([0-9P]+)-(.*)$/);
  if (!m) throw new Error('Unparseable: ' + filename);
  if (m[1] !== cfg.prefix) throw new Error('Prefix mismatch for ' + cfg.folder + ': ' + filename);

  const pageTok = m[2];
  let sideTok = null;
  let side = null;
  let locationRaw = m[3];
  if (cfg.sides) {
    const sm = locationRaw.match(/^(L|R|LR|V)-(.*)$/i);
    if (!sm) throw new Error('No side token: ' + filename);
    sideTok = sm[1].toLowerCase();
    side = SIDE_NAMES[sideTok];
    locationRaw = sm[2];
  }
  const location = locationRaw.replace(/_/g, ' ').trim();
  const page = pageTok.indexOf('P') !== -1 ? pageTok.replace('P', '\u2013') : pageTok;

  let id = cfg.prefix.toLowerCase() + '-p' + pageTok.toLowerCase();
  if (cfg.sides) id += '-' + sideTok;
  id += '-' + slugify(location);
  if (!grid) id += '-nogrid';

  return {
    id: id,
    filename: filename,
    src: 'library/battlemaps/' + cfg.folder + '/' + filename,
    book: cfg.book,
    folder: cfg.folder,
    page: page,
    side: side,
    location: location,
    grid: grid
  };
}

function pageOrder(pageTok) {
  const n = parseInt(pageTok, 10);
  return isNaN(n) ? 9999 : n;
}

const entries = [];
for (const cfg of BOOKS) {
  const dir = path.join(ROOT, 'library', 'battlemaps', cfg.folder);
  const files = fs.readdirSync(dir)
    .filter((f) => /\.jpe?g$/i.test(f))
    .sort((a, b) => {
      const ea = path.basename(a, path.extname(a));
      const eb = path.basename(b, path.extname(b));
      return ea.localeCompare(eb, undefined, { numeric: true, sensitivity: 'base' });
    });
  for (const f of files) {
    entries.push(parseEntry(cfg, f));
  }
}

entries.sort((a, b) => {
  const bi = BOOKS.findIndex((x) => x.book === a.book) - BOOKS.findIndex((x) => x.book === b.book);
  if (bi !== 0) return bi;
  const pa = parseInt(a.page, 10) || 9999;
  const pb = parseInt(b.page, 10) || 9999;
  if (pa !== pb) return pa - pb;
  const sa = a.side || '';
  const sb = b.side || '';
  if (sa !== sb) return sa.localeCompare(sb);
  if (a.grid !== b.grid) return a.grid ? -1 : 1;
  return a.filename.localeCompare(b.filename);
});

const ids = new Map();
for (const e of entries) {
  if (ids.has(e.id)) {
    throw new Error('Duplicate id ' + e.id + ': ' + ids.get(e.id) + ' vs ' + e.filename);
  }
  ids.set(e.id, e.filename);
}

function jsStr(s) {
  return "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
}

const lines = [];
lines.push('// Generated by scripts/build-battlemaps.js — do not edit by hand; run the script to regenerate.');
lines.push('window.RPG_HELPER = window.RPG_HELPER || {};');
lines.push('window.RPG_HELPER.battlemaps = [');
for (const e of entries) {
  lines.push(
    '  {id: ' + jsStr(e.id) + ', filename: ' + jsStr(e.filename) + ', src: ' + jsStr(e.src) +
    ', book: ' + jsStr(e.book) + ', folder: ' + jsStr(e.folder) + ', page: ' + jsStr(e.page) +
    ', side: ' + (e.side ? jsStr(e.side) : 'null') + ', location: ' + jsStr(e.location) +
    ', grid: ' + (e.grid ? 'true' : 'false') + '},'
  );
}
lines.push('];');
fs.writeFileSync(OUT, lines.join('\n') + '\n');

console.log('Wrote ' + OUT);
console.log('  entries: ' + entries.length);
for (const cfg of BOOKS) {
  const n = entries.filter((e) => e.book === cfg.book).length;
  console.log('  ' + cfg.book + ': ' + n);
}
